"""Write include/e2e_keys.h: the network key, the only compiled-in key.

Pair keys are not generated here: two handsets make theirs by pairing and
keep it in NVS. Replacing the network key means reflashing every board.
This project commits the key file; see README.md.
"""
import argparse
import secrets
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "include" / "e2e_keys.h"


def render() -> str:
    key = secrets.token_bytes(16)
    rows = [key[:8], key[8:]]
    literal = "\n".join(
        "    " + ", ".join(f"0x{byte:02X}" for byte in row) + ","
        for row in rows
    )
    return "\n".join([
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/generate_keys.py. Committed on purpose: this is a",
        "// school project and the key protects nothing of value.",
        "namespace e2e_keys",
        "{",
        "// HMAC-SHA256 hop key shared by every handset (and any relay).",
        "constexpr uint8_t network[16] = {",
        literal,
        "};",
        "}",
    ]) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true",
                        help="replace an existing key file")
    args = parser.parse_args()
    if TARGET.exists() and not args.force:
        print(f"{TARGET} already exists; pass --force to replace it.")
        print("Replacing the network key means reflashing EVERY board.")
        return 1
    TARGET.write_text(render())
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
