"""Write include/espnow_keys.h with random PMK and LMK values."""

import secrets
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "include" / "espnow_keys.h"


def key_lines() -> str:
    data = secrets.token_bytes(16)
    rows = [data[:8], data[8:]]
    return "\n".join(
        "    " + ", ".join(f"0x{byte:02X}" for byte in row) + "," for row in rows
    )


def main() -> int:
    if TARGET.exists() and "--force" not in sys.argv:
        print(f"{TARGET} already exists; pass --force to replace it.")
        print("Replacing keys means reflashing BOTH boards.")
        return 1
    TARGET.write_text(
        "#pragma once\n\n#include <stdint.h>\n\n"
        "// Generated by tools/generate_keys.py. Do not commit this file.\n"
        "namespace EspNowKeys {\n"
        f"constexpr uint8_t pmk[16] = {{\n{key_lines()}\n}};\n"
        f"constexpr uint8_t lmk[16] = {{\n{key_lines()}\n}};\n"
        "}  // namespace EspNowKeys\n"
    )
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
