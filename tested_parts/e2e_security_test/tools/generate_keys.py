"""Write include/e2e_keys.h: a network key plus one key per handset pair.

The file holds every pair key, but each board's build compiles only the
block for its own E2E_DEVICE_ID, so a board never holds another pair's key.
"""

import argparse
import itertools
import secrets
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "include" / "e2e_keys.h"


def key_literal(data: bytes, indent: str) -> str:
    rows = [data[:8], data[8:]]
    return "\n".join(
        indent + ", ".join(f"0x{byte:02X}" for byte in row) + ","
        for row in rows
    )


def render(devices: int) -> str:
    network = secrets.token_bytes(16)
    pairs = {
        pair: secrets.token_bytes(16)
        for pair in itertools.combinations(range(1, devices + 1), 2)
    }
    lines = [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/generate_keys.py. Do not commit this file.",
        "// Include through key_store.h, which defines peer_key.",
        "namespace e2e_keys",
        "{",
        "// HMAC-SHA256 hop key shared by handsets and relays.",
        "constexpr uint8_t network[16] = {",
        key_literal(network, "    "),
        "};",
        "",
    ]
    for device in range(1, devices + 1):
        keyword = "#if" if device == 1 else "#elif"
        lines.append(f"{keyword} E2E_DEVICE_ID == {device}")
        lines.append("constexpr key_store::peer_key peer_keys[] = {")
        for peer in range(1, devices + 1):
            if peer == device:
                continue
            pair = (min(device, peer), max(device, peer))
            lines.append(f"    {{{peer}, {{  // Pair {pair[0]}-{pair[1]}")
            lines.append(key_literal(pairs[pair], "        "))
            lines.append("    }},")
        lines.append("};")
    lines.append("#else")
    lines.append(
        f'#error "No keys for this E2E_DEVICE_ID: rerun generate_keys.py '
        f'--devices N"'
    )
    lines.append("#endif")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--devices", type=int, default=3,
                        help="number of handset device IDs (default 3)")
    parser.add_argument("--force", action="store_true",
                        help="replace an existing key file")
    args = parser.parse_args()
    if args.devices < 2:
        parser.error("--devices must be at least 2")
    if TARGET.exists() and not args.force:
        print(f"{TARGET} already exists; pass --force to replace it.")
        print("Replacing keys means reflashing EVERY board.")
        return 1
    TARGET.write_text(render(args.devices))
    print(f"Wrote {TARGET} for devices 1-{args.devices}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
