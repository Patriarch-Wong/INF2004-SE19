"""Write include/e2e_keys.h: the network key and the 1-2 pair key.

As in stages 1-3 (e2e_security_test), the pair key is generated here and
compiled in, so there is no pairing step. The file holds both boards'
blocks; each board's build compiles only the block for its E2E_DEVICE_ID.
At every boot the two boards derive a fresh session key from the pair key
(stage 4's handshake, automatic). Keep the file out of git: it is the
secret. Replacing it means reflashing both boards.
"""

import argparse
import secrets
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "include" / "e2e_keys.h"


def key_literal(data: bytes, indent: str) -> str:
    rows = [data[:8], data[8:]]
    return "\n".join(
        indent + ", ".join(f"0x{byte:02X}" for byte in row) + ","
        for row in rows
    )


def render() -> str:
    network = secrets.token_bytes(16)
    pair = secrets.token_bytes(16)
    lines = [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/generate_keys.py. Committed on purpose; see README.",
        "// Each board compiles only its own block (E2E_DEVICE_ID).",
        "namespace e2e_keys",
        "{",
        "struct peer_key",
        "{",
        "    uint8_t peer;",
        "    uint8_t key[16];",
        "};",
        "",
        "// HMAC-SHA256 hop key shared by both boards.",
        "constexpr uint8_t network[16] = {",
        key_literal(network, "    "),
        "};",
        "",
    ]
    for device, peer in ((1, 2), (2, 1)):
        keyword = "#if" if device == 1 else "#elif"
        lines += [
            f"{keyword} E2E_DEVICE_ID == {device}",
            "constexpr peer_key peer_keys[] = {",
            f"    {{{peer}, {{  // Pair 1-2",
            key_literal(pair, "        "),
            "    }},",
            "};",
        ]
    lines += [
        "#else",
        '#error "No keys for this E2E_DEVICE_ID: build board1 or board2"',
        "#endif",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true",
                        help="replace an existing key file")
    args = parser.parse_args()
    if TARGET.exists() and not args.force:
        print(f"{TARGET} already exists; pass --force to replace it.")
        print("Replacing keys means reflashing BOTH boards.")
        return 1
    TARGET.write_text(render())
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
