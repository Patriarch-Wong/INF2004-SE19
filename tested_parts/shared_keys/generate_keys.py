"""Write shared_keys/e2e_keys.h: the network key and one pair key per pair
of boards, for up to --boards handsets (default 5). Every project that uses
these keys reads this one file, so all boards share the same keys whichever
project they run.

Pre-pairing, as in stages 1-3 (e2e_security_test): pair keys are generated
here and compiled in, so there is no pairing step. Boards a and b share the
pair key "a-b"; no other board has it. The file holds every board's block,
and each board's build compiles only the block for its E2E_DEVICE_ID, so a
board's firmware holds only its own pair keys. At every boot each pair
derives a fresh session key from its pair key (stage 4's handshake).

By default an existing file is extended: its network key and pair keys are
kept, and only missing pairs get new keys, so boards already flashed keep
working. --force replaces every key (then reflash every board). --check
only verifies the file.
"""

import argparse
import re
import secrets
import sys
from itertools import combinations
from pathlib import Path

TARGET = Path(__file__).resolve().parent / "e2e_keys.h"
MAX_BOARDS = 8
BYTE = r"0x([0-9A-Fa-f]{2})"


def key_literal(data: bytes, indent: str) -> str:
    rows = [data[:8], data[8:]]
    return "\n".join(
        indent + ", ".join(f"0x{byte:02X}" for byte in row) + ","
        for row in rows
    )


def parse(text: str):
    """Returns (network key, {(a, b): key}) from an existing file."""
    match = re.search(r"network\[16\]\s*=\s*\{([^}]*)\}", text)
    network = bytes(int(b, 16) for b in re.findall(BYTE, match.group(1))) \
        if match else None
    if network is not None and len(network) != 16:
        raise ValueError("network key is not 16 bytes")
    pairs = {}
    # Each entry: {peer, {  // Pair a-b  then 16 bytes, inside a block for
    # E2E_DEVICE_ID == device.
    for block in re.finditer(
            r"E2E_DEVICE_ID == (\d+)(.*?)(?=#elif|#else|#endif)", text,
            re.S):
        device = int(block.group(1))
        for entry in re.finditer(r"\{(\d+), \{[^\n]*\n([^}]*)\}\}",
                                 block.group(2)):
            peer = int(entry.group(1))
            key = bytes(int(b, 16) for b in re.findall(BYTE, entry.group(2)))
            if len(key) != 16:
                raise ValueError(f"key {device}-{peer} is not 16 bytes")
            pair = (min(device, peer), max(device, peer))
            if pair in pairs and pairs[pair] != key:
                raise ValueError(f"pair {pair[0]}-{pair[1]} differs between "
                                 "its two boards")
            pairs[pair] = key
    return network, pairs


def check(network, pairs, boards: int) -> list:
    problems = []
    if network is None or not any(network):
        problems.append("network key missing or all zero")
    for a, b in combinations(range(1, boards + 1), 2):
        key = pairs.get((a, b))
        if key is None:
            problems.append(f"pair {a}-{b} missing")
        elif not any(key):
            problems.append(f"pair {a}-{b} is all zero")
    keys = [k for k in pairs.values()] + ([network] if network else [])
    if len(set(keys)) != len(keys):
        problems.append("two keys are identical")
    return problems


def render(network: bytes, pairs: dict, boards: int) -> str:
    lines = [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by shared_keys/generate_keys.py. Committed on purpose; see",
        "// shared_keys/README.md. One file for every project.",
        f"// Pre-pairing for {boards} handsets: one pair key per pair of boards.",
        "// Each board compiles only its own block (E2E_DEVICE_ID), so its",
        "// firmware holds only the pair keys it shares with the others.",
        "// Relay builds (E2E_RELAY) and projects that make pair keys by",
        "// pairing (E2E_NETWORK_KEY_ONLY) get the network key only.",
        "namespace e2e_keys",
        "{",
        "struct peer_key",
        "{",
        "    uint8_t peer;",
        "    uint8_t key[16];",
        "};",
        "",
        "// HMAC-SHA256 hop key shared by every board.",
        "constexpr uint8_t network[16] = {",
        key_literal(network, "    "),
        "};",
        "",
    ]
    lines += [
        "#if defined(E2E_RELAY) || defined(E2E_NETWORK_KEY_ONLY)",
        "// Network key only: no pair keys in this build.",
    ]
    for device in range(1, boards + 1):
        lines += [f"#elif E2E_DEVICE_ID == {device}",
                  "constexpr peer_key peer_keys[] = {"]
        for peer in range(1, boards + 1):
            if peer == device:
                continue
            a, b = min(device, peer), max(device, peer)
            lines += [
                f"    {{{peer}, {{  // Pair {a}-{b}",
                key_literal(pairs[(a, b)], "        "),
                "    }},",
            ]
        lines.append("};")
    lines += [
        "#else",
        f'#error "No keys for this E2E_DEVICE_ID: build board1..board{boards}"',
        "#endif",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--boards", type=int, default=5,
                        help="number of handsets, 2..%d (default 5)" %
                        MAX_BOARDS)
    parser.add_argument("--force", action="store_true",
                        help="replace every key; reflash every board")
    parser.add_argument("--check", action="store_true",
                        help="verify the existing file only")
    args = parser.parse_args()
    if not 2 <= args.boards <= MAX_BOARDS:
        parser.error(f"--boards must be 2..{MAX_BOARDS}")

    network, pairs = None, {}
    if TARGET.exists() and not args.force:
        try:
            network, pairs = parse(TARGET.read_text())
        except ValueError as error:
            print(f"{TARGET}: {error}")
            return 1

    if args.check:
        problems = check(network, pairs, args.boards)
        for problem in problems:
            print(f"FAIL: {problem}")
        if problems:
            return 1
        print(f"Key file OK: network key and all "
              f"{len(list(combinations(range(args.boards), 2)))} pair keys "
              f"for {args.boards} boards, both sides match, all distinct")
        return 0

    if network is None or not any(network):
        network = secrets.token_bytes(16)
    added = []
    for pair in combinations(range(1, args.boards + 1), 2):
        if pair not in pairs:
            pairs[pair] = secrets.token_bytes(16)
            added.append(pair)
    TARGET.write_text(render(network, pairs, args.boards))
    kept = len(list(combinations(range(args.boards), 2))) - len(added)
    print(f"Wrote {TARGET}: {args.boards} boards, kept {kept} pair key(s), "
          f"added {len(added)}"
          + (": " + ", ".join(f"{a}-{b}" for a, b in added) if added else ""))
    if args.force:
        print("Every key is new: reflash every board.")
    elif added:
        print("Existing keys unchanged; only boards with a new pair need "
              "reflashing to use it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
